# Concurrency locks and cached font properties for PDF export
_pdf_export_lock = threading.Lock()
_tamil_font_prop = None
_font_lock = threading.Lock()

def _get_tamil_font_properties() -> fm.FontProperties:
    """Thread-safe lazy initializer for Tamil Unicode font properties."""
    global _tamil_font_prop
    if _tamil_font_prop is not None:
        return _tamil_font_prop

    with _font_lock:
        if _tamil_font_prop is not None:
            return _tamil_font_prop

        base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        bundled_font = os.path.join(base_dir, 'app', 'static', 'fonts', 'NotoSansTamil-Regular.ttf')

        candidate_paths = [
            bundled_font,
            r'C:\Windows\Fonts\Nirmala.ttf',
            r'C:\Windows\Fonts\latha.ttf',
            '/usr/share/fonts/truetype/noto/NotoSansTamil-Regular.ttf',
        ]

        for p in candidate_paths:
            if os.path.exists(p):
                try:
                    fm.fontManager.addfont(p)
                    _tamil_font_prop = fm.FontProperties(fname=p)
                    break
                except Exception:
                    continue

        if _tamil_font_prop is None:
            _tamil_font_prop = fm.FontProperties(family='sans-serif')

        return _tamil_font_prop

def format_prediction_result(class_id: int, confidence: float) -> Dict[str, Any]:
    """Formats a single prediction into a structured response."""
    tamil_char = get_unicode_char(class_id)
    codepoints = get_unicode_codepoints(class_id)
    return {
        'class_id': int(class_id),
        'unicode': tamil_char,
        'codepoints': codepoints,
        'confidence': round(float(confidence), 4),
        'confidence_percent': round(float(confidence) * 100.0, 2)
    }

def export_to_txt(text: str) -> io.BytesIO:
    """
    Exports Tamil Unicode string to a clean UTF-8 plain text file buffer.
    Normalizes line endings (CRLF / CR -> LF).
    """
    buf = io.BytesIO()
    normalized = text.replace('\r\n', '\n').replace('\r', '\n')
    buf.write(normalized.encode('utf-8'))
    buf.seek(0)
    return buf

def export_to_docx(text: str, title: str = "Tamil Handwritten OCR Output") -> io.BytesIO:
    """
    Exports Tamil Unicode string to a Microsoft Word (.docx) document buffer.
    Configures standard 1-inch margins, 13pt Tamil body typography, line-by-line
    paragraphs with 1.3 line spacing, and explicit Word OpenXML complex script (w:cs)
    attributes for native Tamil rendering across all Word versions.
    """
    import docx
    from docx.shared import Pt, Inches, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = docx.Document()

    # 1. Page Margins (1.0 inch all around)
    for section in doc.sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)

    # 2. Document Title
    heading = doc.add_heading(level=1)
    run_title = heading.add_run(title)
    run_title.font.name = 'Segoe UI'
    run_title.font.size = Pt(18)
    run_title.font.bold = True
    run_title.font.color.rgb = RGBColor(15, 23, 42)  # Slate 900
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    heading.paragraph_format.space_before = Pt(0)
    heading.paragraph_format.space_after = Pt(4)

    # 3. Subtitle / Metadata
    p_meta = doc.add_paragraph()
    r_meta = p_meta.add_run("Generated by Tamil Handwritten Character Recognition and Unicode Conversion System")
    r_meta.font.name = 'Segoe UI'
    r_meta.font.size = Pt(9.5)
    r_meta.font.italic = True
    r_meta.font.color.rgb = RGBColor(100, 116, 139)  # Slate 500
    p_meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_meta.paragraph_format.space_before = Pt(0)
    p_meta.paragraph_format.space_after = Pt(20)

    # 4. Content Section: Individual paragraph per logical line
    lines = text.replace('\r\n', '\n').replace('\r', '\n').split('\n')
    for line in lines:
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.3
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.space_before = Pt(0)

        if line:
            r = p.add_run(line)
            r.font.name = 'Nirmala UI'
            r.font.size = Pt(13)
            r.font.color.rgb = RGBColor(15, 23, 42)

            # Explicitly set Word OpenXML complex script (w:cs) and size (w:szCs) attributes
            rPr = r._r.get_or_add_rPr()
            rFonts = rPr.find(docx.oxml.ns.qn('w:rFonts'))
            if rFonts is None:
                rFonts = docx.oxml.OxmlElement('w:rFonts')
                rPr.append(rFonts)
            rFonts.set(docx.oxml.ns.qn('w:cs'), 'Nirmala UI')
            rFonts.set(docx.oxml.ns.qn('w:ascii'), 'Nirmala UI')
            rFonts.set(docx.oxml.ns.qn('w:hAnsi'), 'Nirmala UI')

            szCs = rPr.find(docx.oxml.ns.qn('w:szCs'))
            if szCs is None:
                szCs = docx.oxml.OxmlElement('w:szCs')
                rPr.append(szCs)
            szCs.set(docx.oxml.ns.qn('w:val'), '26')  # 26 half-points = 13pt

    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf

def export_to_pdf(text: str, title: str = "Tamil Handwritten OCR Output") -> io.BytesIO:
    """
    Exports Tamil Unicode text to a clean, professionally-formatted PDF buffer.
    Uses Matplotlib's vector engine (FreeType / HarfBuzz shaping) with the bundled
    NotoSansTamil-Regular font to render complex Tamil conjuncts, ligatures, two-part
    vowels, and viramas with full typographic fidelity.

    Concurrency Hardening (Phase U10):
    - Uses pure object-oriented Figure and FigureCanvasAgg/FigureCanvasPdf instances,
      avoiding any reliance on matplotlib.pyplot global state.
    - Synchronized via _pdf_export_lock to ensure thread-safe rendering under
      concurrent multi-threaded Gunicorn requests.
    - Cached font properties via _get_tamil_font_properties().
    """
    from matplotlib.figure import Figure
    from matplotlib.backends.backend_agg import FigureCanvasAgg
    from matplotlib.backends.backend_pdf import PdfPages, FigureCanvasPdf

    tamil_prop = _get_tamil_font_properties()

    with _pdf_export_lock:
        # 1. Page Geometry & Typography Metrics
        page_width_in, page_height_in = 8.5, 11.0
        margin_x_in = 0.8
        margin_top_in = 0.8
        margin_bot_in = 0.8
        usable_width_in = page_width_in - (2 * margin_x_in)
        usable_width_pt = usable_width_in * 72.0

        title_fontsize = 16
        sub_fontsize = 9.5
        body_fontsize = 13
        line_height_pt = body_fontsize * 1.55
        line_height_in = line_height_pt / 72.0

        # 2. Margin-Aware Word Wrapping (using isolated Figure & Agg Canvas)
        lines_raw = text.replace('\r\n', '\n').replace('\r', '\n').split('\n') if text else []

        fig_temp = Figure(figsize=(page_width_in, page_height_in), dpi=100)
        canvas_temp = FigureCanvasAgg(fig_temp)
        ax_temp = fig_temp.add_axes([0, 0, 1, 1])
        renderer = canvas_temp.get_renderer()

        wrapped_lines = []
        for raw_l in lines_raw:
            if not raw_l.strip():
                wrapped_lines.append('')
                continue
            words = raw_l.split(' ')
            current_line = []
            for word in words:
                test_line = ' '.join(current_line + [word])
                t = ax_temp.text(0, 0, test_line, fontproperties=tamil_prop, fontsize=body_fontsize)
                bbox = t.get_window_extent(renderer=renderer)
                w_pt = bbox.width * 72.0 / 100.0
                t.remove()
                if w_pt <= usable_width_pt or not current_line:
                    current_line.append(word)
                else:
                    wrapped_lines.append(' '.join(current_line))
                    current_line = [word]
            if current_line:
                wrapped_lines.append(' '.join(current_line))
        fig_temp.clear()

        if not wrapped_lines:
            wrapped_lines = ['']

        # 3. Multi-Page Pagination
        header_height_in = 0.85
        first_page_usable_h = page_height_in - margin_top_in - margin_bot_in - header_height_in
        other_page_usable_h = page_height_in - margin_top_in - margin_bot_in

        lines_per_first_page = max(1, int(first_page_usable_h / line_height_in))
        lines_per_other_page = max(1, int(other_page_usable_h / line_height_in))

        pages_lines = []
        if len(wrapped_lines) <= lines_per_first_page:
            pages_lines.append(wrapped_lines)
        else:
            pages_lines.append(wrapped_lines[:lines_per_first_page])
            remainder = wrapped_lines[lines_per_first_page:]
            while remainder:
                pages_lines.append(remainder[:lines_per_other_page])
                remainder = remainder[lines_per_other_page:]

        total_pages = len(pages_lines)

        # 4. Render Pages to PDF Buffer (using isolated Figure & PdfCanvas)
        buf = io.BytesIO()
        with PdfPages(buf) as pdf:
            for p_idx, page_content in enumerate(pages_lines):
                fig = Figure(figsize=(page_width_in, page_height_in), dpi=150)
                canvas = FigureCanvasPdf(fig)
                ax = fig.add_axes([0, 0, 1, 1])
                ax.set_xlim(0, page_width_in)
                ax.set_ylim(0, page_height_in)
                ax.axis('off')

                y_cursor = page_height_in - margin_top_in

                # Document Header (First page only)
                if p_idx == 0:
                    is_tamil_title = any('\u0b80' <= c <= '\u0bff' for c in title)
                    title_font = {'fontproperties': tamil_prop} if is_tamil_title else {'family': 'sans-serif'}
                    ax.text(page_width_in / 2.0, y_cursor, title,
                            ha='center', va='top', fontsize=title_fontsize, fontweight='bold',
                            color='#0f172a', **title_font)
                    y_cursor -= (title_fontsize * 1.3 / 72.0)

                    ax.text(page_width_in / 2.0, y_cursor,
                            'Generated by Tamil Handwritten Character Recognition and Unicode Conversion System',
                            ha='center', va='top', fontsize=sub_fontsize, fontstyle='italic',
                            color='#64748b', family='sans-serif')
                    y_cursor -= (sub_fontsize * 1.6 / 72.0)

                    # Header Separator Rule
                    ax.plot([margin_x_in, page_width_in - margin_x_in], [y_cursor, y_cursor],
                            color='#cbd5e1', lw=0.75)
                    y_cursor -= 0.30

                # Content Lines
                for line in page_content:
                    if line:
                        ax.text(margin_x_in, y_cursor, line,
                                ha='left', va='top', fontproperties=tamil_prop,
                                fontsize=body_fontsize, color='#0f172a')
                    y_cursor -= line_height_in

                # Footer Page Number
                ax.text(page_width_in / 2.0, margin_bot_in / 2.0,
                        f'Page {p_idx + 1} of {total_pages}',
                        ha='center', va='center', fontsize=9, color='#94a3b8', family='sans-serif')

                pdf.savefig(fig)
                fig.clear()

        buf.seek(0)
        return buf
